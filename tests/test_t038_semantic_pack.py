def _make_synthetic_fpga_project(base: Path) -> Path:
    """Create a minimal synthetic FPGA project for reproducible testing."""
    proj = base / "fpga_project_synth_test"

    # L5 fixed-point Python model
    l5 = proj / "src" / "python_model" / "L5_fixedpoint"
    l5.mkdir(parents=True)
    (l5 / "synth_test_l5.py").write_text(
        "def compute_peak_idx(signal):\n"
        "    '''Detect peak index in signal.'''\n"
        "    max_val = max(signal)\n"
        "    return signal.index(max_val)\n"
        "\n"
        "class PeakDetector:\n"
        "    def __init__(self, threshold):\n"
        "        self.threshold = threshold\n"
        "\n"
        "def normalize_window(window):\n"
        "    return [x / sum(window) for x in window]\n",
        encoding="utf-8",
    )

    # L6 resource-optimized Python model
    l6 = proj / "src" / "python_model" / "L6_resource_opt"
    l6.mkdir(parents=True)
    (l6 / "synth_test_l6.py").write_text(
        "def optimized_peak_idx(signal, window_size):\n"
        "    '''Optimized peak detection.'''\n"
        "    return compute_peak_idx(signal[:window_size])\n"
        "\n"
        "class PeakDetectorOpt:\n"
        "    pass\n",
        encoding="utf-8",
    )

    # RTL Verilog model
    rtl = proj / "src" / "verilog_model" / "rtl"
    rtl.mkdir(parents=True)
    (rtl / "peak_detector.v").write_text(
        "module peak_detector (\n"
        "    input clk,\n"
        "    input [15:0] signal_in,\n"
        "    output [7:0] peak_idx_out\n"
        ");\n"
        "    reg [7:0] peak_idx;\n"
        "    always @(posedge clk) begin\n"
        "        peak_idx <= peak_idx + 1;\n"
        "    end\n"
        "    assign peak_idx_out = peak_idx;\n"
        "endmodule\n",
        encoding="utf-8",
    )
    (rtl / "normalizer.v").write_text(
        "module normalizer (\n"
        "    input [15:0] window [0:7],\n"
        "    output [15:0] norm_out [0:7]\n"
        ");\n"
        "    assign norm_out = window;\n"
        "endmodule\n",
        encoding="utf-8",
    )

    # Tests
    tests = proj / "tests"
    tests.mkdir(parents=True)
    (tests / "test_peak.py").write_text(
        "import pytest\n"
        "\n"
        "def test_peak_idx_basic():\n"
        "    assert compute_peak_idx([1, 2, 3]) == 2\n"
        "\n"
        "def test_normalize_window():\n"
        "    assert sum(normalize_window([1, 1, 1])) == 1.0\n",
        encoding="utf-8",
    )

    return proj


def test_reproducible_bundle_generation(tmp_path: Path) -> None:
    """Generate a bundle from a synthetic project on-the-fly."""
    proj = _make_synthetic_fpga_project(tmp_path)
    out_dir = tmp_path / "bundle_out"

    metadata = run_p1b_trace_project(
        project_root=proj,
        concepts=["auto"],
        out_dir=out_dir,
        max_concepts=8,
    )

    # Check metadata
    assert metadata.get("status") in ("ok", "partial"), (
        f"Unexpected status: {metadata.get('status')}"
    )
    assert metadata.get("semantic_summary_status") == "ok", (
        f"semantic_summary_status must be ok, got {metadata.get('semantic_summary_status')}"
    )
    assert "project_semantic_summary.json" in metadata.get("artifacts", []), (
        "project_semantic_summary.json must be in artifacts"
    )

    # Check files exist
    assert (out_dir / "project_semantic_summary.json").is_file()
    assert (out_dir / "run_metadata.json").is_file()
    assert (out_dir / "project_understanding_graph.json").is_file()
    assert (out_dir / "project_understanding_index.json").is_file()

    # Check semantic summary schema
    ss = _load_json(out_dir / "project_semantic_summary.json")
    assert "l5_l6_to_rtl_summary" in ss, "semantic summary must have l5_l6_to_rtl_summary"
    assert ss["schema_version"] == "project-semantic-summary-0.1"
    assert len(ss["pipeline_stages"]) >= 1, "must have at least 1 pipeline stage"
    assert len(ss["core_concepts"]) >= 1, "must have at least 1 core concept"

    # Check l5_l6_to_rtl_summary structure
    l5rtl = ss["l5_l6_to_rtl_summary"]
    assert "concept_mappings" in l5rtl
    assert "summary" in l5rtl
    for cm in l5rtl["concept_mappings"]:
        assert "concept" in cm
        assert "l5_l6_sources" in cm
        assert "rtl_targets" in cm
        assert "mapping_confidence" in cm
        assert "mapping_reason" in cm
        assert "gaps" in cm

    # Check index has semantic_summary_path
    idx = _load_json(out_dir / "project_understanding_index.json")
    assert idx.get("semantic_summary_path") == "project_semantic_summary.json", (
        "index must reference semantic_summary_path"
    )
