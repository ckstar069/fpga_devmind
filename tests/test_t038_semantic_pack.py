def test_semantic_summary_schema(bundle_dir: Path) -> None:
    ss = _load_json(bundle_dir / "project_semantic_summary.json")
    required_top = [
        "schema_version", "project_id", "project_root", "project_kind_hint",
        "top_level_purpose", "pipeline_stages", "core_concepts",
        "implementation_modules", "dataflow_summary", "l5_l6_to_rtl_summary",
        "evidence_quality_summary", "uncertainty_summary", "test_coverage_summary",
        "source_provenance",
    ]
    for field in required_top:
        assert field in ss, f"semantic_summary missing top-level field: {field}"

    assert ss["schema_version"] == "project-semantic-summary-0.1"
    assert isinstance(ss["pipeline_stages"], list)
    assert isinstance(ss["core_concepts"], list)
    assert isinstance(ss["implementation_modules"], list)

    # l5_l6_to_rtl_summary
    l5rtl = ss["l5_l6_to_rtl_summary"]
    assert "concept_mappings" in l5rtl, "l5_l6_to_rtl_summary missing concept_mappings"
    assert "summary" in l5rtl, "l5_l6_to_rtl_summary missing summary"
    for cm in l5rtl["concept_mappings"]:
        assert "concept" in cm
        assert "l5_l6_sources" in cm
        assert "rtl_targets" in cm
        assert "mapping_confidence" in cm
        assert "mapping_reason" in cm
        assert "gaps" in cm

    # Evidence quality summary
    ev = ss["evidence_quality_summary"]
    for field in ["strong_direct", "medium_structural", "weak_name_only", "inferred"]:
        assert field in ev, f"evidence_quality_summary missing {field}"
        assert isinstance(ev[field], int)

    # Uncertainty summary
    unc = ss["uncertainty_summary"]
    for field in ["inferred_claims", "weak_only_links", "naming_only_links",
                  "missing_l5_l6", "missing_rtl", "missing_test_evidence"]:
        assert field in unc, f"uncertainty_summary missing {field}"

    # Test coverage summary
    tc = ss["test_coverage_summary"]
    for field in ["test_files_present", "total_test_files",
                  "concepts_with_test_match", "concepts_without_test_match", "per_concept"]:
        assert field in tc, f"test_coverage_summary missing {field}"

    # Source provenance
    prov = ss["source_provenance"]
    assert "summary_generated_from" in prov
    assert "generation_timestamp" in prov
    assert "generator" in prov


